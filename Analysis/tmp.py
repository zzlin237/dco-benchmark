# 创建DataFrame
df = pd.DataFrame(data)

# 横纵坐标互调：转置数据
df_transposed = df.T  # 转置数据，使方法为行，数据点为列

# 计算每类方法与FDScanning的比值，并转换为百分比形式（保留两位小数）
methods = ["PDScanning", "RPDScanning", "ADSamping", "DADE", "DDCres", "DDCpca", "DDCopq"]
# 创建一个新DataFrame用于存储比值
ratio_data = {}

for method in methods:
    # 计算每个方法与FDScanning的比值
    ratio_values = (df_transposed.loc[method] / df_transposed.loc["FDScanning"] * 100).round(2).astype(str) + "%"
    ratio_data[f"{method}/FDScanning"] = ratio_values

# 将比值数据转换为DataFrame
ratio_df = pd.DataFrame(ratio_data)

# 合并原始转置数据和比值数据
result_df = pd.concat([df_transposed, ratio_df.T], axis=0)

# 保存结果到Excel文件
output_file = "scanning_ratios_transposed.xlsx"
result_df.to_excel(output_file, index=True)

